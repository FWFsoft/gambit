@dataclass
class Key:
    t: float                       # 0..1 through the clip
    pose: Dict[str, Sequence[float]]
    offset: Sequence[float] = (0, 0, 0)   # root translation (model space)
    rot: Sequence[float] = (0, 0, 0)      # root rotation (degrees)
    ease: str = "smooth"                  # into this key: smooth|linear|in|out


@dataclass
class Clip:
    name: str
    frames: int
    fps: int
    loop: bool
    keys: List[Key]


def _ease(kind, u):
    if kind == "linear":
        return u
    if kind == "in":
        return u * u
    if kind == "out":
        return 1 - (1 - u) * (1 - u)
    return u * u * (3 - 2 * u)


def _lerp3(a, b, u):
    return tuple(a[i] + (b[i] - a[i]) * u for i in range(3))


def sample(clip: Clip, t: float, base: Dict[str, Sequence[float]]):
    """Pose at time t (0..1). Joints missing from a key use `base`."""
    keys = clip.keys
    if t <= keys[0].t:
        k0 = k1 = keys[0]
        u = 0.0
    elif t >= keys[-1].t:
        k0 = k1 = keys[-1]
        u = 0.0
    else:
        for i in range(len(keys) - 1):
            if keys[i].t <= t <= keys[i + 1].t:
                k0, k1 = keys[i], keys[i + 1]
                span = max(1e-6, k1.t - k0.t)
                u = _ease(k1.ease, (t - k0.t) / span)
                break
    names = set(base) | set(k0.pose) | set(k1.pose)
    pose = {}
    for n in names:
        a = k0.pose.get(n, base.get(n, (0, 0, 0)))
        b = k1.pose.get(n, base.get(n, (0, 0, 0)))
        pose[n] = _lerp3(a, b, u)
    return pose, _lerp3(k0.offset, k1.offset, u), _lerp3(k0.rot, k1.rot, u)


