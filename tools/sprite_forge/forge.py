class Renderer:
    def __init__(self, cell_w: int, cell_h: int, pivot_y: int):
        self.cell_w, self.cell_h, self.pivot_y = cell_w, cell_h, pivot_y
        sc = bpy.context.scene
        sc.render.engine = "CYCLES"
        sc.cycles.device = "CPU"
        sc.cycles.samples = 1
        sc.cycles.use_denoising = False
        sc.cycles.max_bounces = 0
        sc.cycles.filter_width = 0.01
        sc.cycles.seed = 0
        sc.render.film_transparent = True
        sc.render.dither_intensity = 0.0
        sc.render.resolution_x = cell_w
        sc.render.resolution_y = cell_h
        sc.render.resolution_percentage = 100
        sc.render.image_settings.file_format = "PNG"
        sc.render.image_settings.color_mode = "RGBA"
        sc.render.image_settings.color_depth = "16"
        sc.view_settings.view_transform = "Raw"
        sc.view_settings.look = "None"
        sc.view_settings.exposure = 0.0
        sc.view_settings.gamma = 1.0
        sc.world = bpy.data.worlds.new("forge_world")
        sc.world.use_nodes = True
        bg = sc.world.node_tree.nodes.get("Background")
        if bg:
            bg.inputs["Strength"].default_value = 0.0

        cam = bpy.data.cameras.new("forge_cam")
        cam.type = "ORTHO"
        size = max(cell_w, cell_h)
        cam.ortho_scale = size * PIXEL_SIZE
        cam.clip_start = 0.1
        cam.clip_end = 100.0
        # Put the ground origin at (cell_w/2, pivot_y) in the image.
        cam.shift_x = 0.0
        cam.shift_y = (pivot_y - cell_h / 2.0) / size
        obj = bpy.data.objects.new("forge_cam", cam)
        sc.collection.objects.link(obj)
        el = math.radians(CAMERA_ELEVATION_DEG)
        dist = 20.0
        obj.location = (0.0, -dist * math.cos(el), dist * math.sin(el))
        obj.rotation_euler = (math.pi / 2 - el, 0.0, 0.0)
        sc.camera = obj
        self.camera = obj

        self.normal_mat = self._pass_material("normal")
        self.depth_mat = self._pass_material("depth")
        self.tmp = tempfile.mkdtemp(prefix="forge_")

    @staticmethod
    def _pass_material(kind):
        mat = bpy.data.materials.new(f"forge_{kind}")
        mat.use_nodes = True
        nt = mat.node_tree
        nt.nodes.clear()
        out = nt.nodes.new("ShaderNodeOutputMaterial")
        em = nt.nodes.new("ShaderNodeEmission")
        if kind == "normal":
            geo = nt.nodes.new("ShaderNodeNewGeometry")
            # n * 0.5 + 0.5
            mul = nt.nodes.new("ShaderNodeVectorMath")
            mul.operation = "MULTIPLY_ADD"
            mul.inputs[1].default_value = (0.5, 0.5, 0.5)
            mul.inputs[2].default_value = (0.5, 0.5, 0.5)
            nt.links.new(geo.outputs["Normal"], mul.inputs[0])
            nt.links.new(mul.outputs[0], em.inputs["Color"])
        else:
            camd = nt.nodes.new("ShaderNodeCameraData")
            div = nt.nodes.new("ShaderNodeMath")
            div.operation = "DIVIDE"
            div.inputs[1].default_value = 40.0
            nt.links.new(camd.outputs["View Z Depth"], div.inputs[0])
            comb = nt.nodes.new("ShaderNodeCombineColor")
            nt.links.new(div.outputs[0], comb.inputs[0])
            nt.links.new(div.outputs[0], comb.inputs[1])
            nt.links.new(div.outputs[0], comb.inputs[2])
            nt.links.new(comb.outputs[0], em.inputs["Color"])
        nt.links.new(em.outputs[0], out.inputs[0])
        return mat

    def _render(self, override, name):
        vl = bpy.context.view_layer
        vl.material_override = override
        path = os.path.join(self.tmp, name + ".png")
        bpy.context.scene.render.filepath = path
        bpy.ops.render.render(write_still=True)
        vl.material_override = None
        img = np.array(Image.open(path)).astype(np.float32)
        # 16-bit PNG -> 0..1
        return img / 65535.0 if img.max() > 255 else img / 255.0

    def frame(self, model: Model) -> Image.Image:
        idp = self._render(None, "id")
        nrm = self._render(self.normal_mat, "normal")
        dep = self._render(self.depth_mat, "depth")
        return shade(model, idp, nrm, dep)


def shade(model: Model, idp, nrm, dep) -> Image.Image:
    """Turn the three passes into one cel-shaded, outlined pixel sprite."""
    h, w = idp.shape[:2]
    alpha = idp[..., 3] > 0.5
    mat_index = np.rint(idp[..., 0] * 255).astype(int)
    normal = nrm[..., :3] * 2.0 - 1.0
    depth = dep[..., 0] * 40.0
    depth[~alpha] = 1e9

    key = normal @ np.array(KEY_LIGHT)
    fill = normal @ np.array(FILL_LIGHT)
    light = np.clip(key, -1, 1) * 0.85 + np.clip(fill, 0, 1) * 0.25
    # Top-facing surfaces catch a bit more: helps read volume from above.
    light += np.clip(normal[..., 2], 0, 1) * 0.10
    band = np.full((h, w), 2)
    band[light < 0.62] = 2
    band[light < 0.30] = 1
    band[light < 0.02] = 0
    band[light >= 0.80] = 3

    out = np.zeros((h, w, 4), dtype=np.uint8)
    by_index = {m.index: m for m in model.materials.values()}
    for idx, m in by_index.items():
        sel = alpha & (mat_index == idx)
        if not sel.any():
            continue
        ramp = np.array(m.ramp, dtype=np.uint8)
        out[sel, :3] = ramp[band[sel]]
        out[sel, 3] = 255

    # Depth breaks inside the silhouette: the farther pixel gets a line, so
    # an arm in front of the chest stays readable at this size.
    line = np.zeros((h, w), dtype=bool)
    for dy, dx in ((0, 1), (0, -1), (1, 0), (-1, 0)):
        shifted = np.full_like(depth, 1e9)
        ys = slice(max(dy, 0), h + min(dy, 0))
        xs = slice(max(dx, 0), w + min(dx, 0))
        yd = slice(max(-dy, 0), h + min(-dy, 0))
        xd = slice(max(-dx, 0), w + min(-dx, 0))
        shifted[yd, xd] = depth[ys, xs]
        line |= alpha & (depth - shifted > DEPTH_EDGE)
    for idx, m in by_index.items():
        sel = line & (mat_index == idx)
        if sel.any():
            dark = np.array(m.ramp[0], dtype=np.float32) * 0.62 + \
                np.array(OUTLINE_RGB, dtype=np.float32) * 0.38
            out[sel, :3] = dark.astype(np.uint8)

    # Outer outline
    pad = np.pad(alpha, 1)
    neighbour = pad[:-2, 1:-1] | pad[2:, 1:-1] | pad[1:-1, :-2] | pad[1:-1, 2:]
    ring = neighbour & ~alpha
    out[ring, :3] = OUTLINE_RGB
    out[ring, 3] = 255
    return Image.fromarray(out, "RGBA")


