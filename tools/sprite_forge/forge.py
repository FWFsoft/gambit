PIXEL_SIZE = 0.0215          # world units per sprite pixel (1.85u hero ~ 75px)
CAMERA_ELEVATION_DEG = 30.0  # matches the 2:1 isometric tiles
KEY_LIGHT = Vector((-0.55, -0.50, 0.68)).normalized()  # front-left-above
