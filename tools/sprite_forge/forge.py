# --------------------------------------------------------------------------
# Colour ramps
# --------------------------------------------------------------------------

def _rgb_to_hsv(c):
    r, g, b = [x / 255.0 for x in c]
    mx, mn = max(r, g, b), min(r, g, b)
    d = mx - mn
    h = 0.0
    if d > 1e-6:
        if mx == r:
            h = ((g - b) / d) % 6
        elif mx == g:
            h = (b - r) / d + 2
        else:
            h = (r - g) / d + 4
        h /= 6.0
    s = 0.0 if mx < 1e-6 else d / mx
    return h, s, mx


def _hsv_to_rgb(h, s, v):
    h = h % 1.0
    i = int(h * 6)
    f = h * 6 - i
    p, q, t = v * (1 - s), v * (1 - f * s), v * (1 - (1 - f) * s)
    r, g, b = [(v, t, p), (q, v, p), (p, v, t), (p, q, v), (t, p, v), (v, p, q)][i % 6]
    return tuple(int(round(max(0, min(1, x)) * 255)) for x in (r, g, b))


def _shift_hue_toward(h, target, amount):
    d = ((target - h + 0.5) % 1.0) - 0.5
    return h + d * amount


def make_ramp(base, glow=False) -> List[Tuple[int, int, int]]:
    """Shadow, mid, base, highlight. Shadows drift toward violet and lose
    value, highlights drift toward warm yellow and lose saturation: the usual
    pixel-art ramp, applied identically to every material."""
    if glow:
        # Emissive materials (eyes, venom) barely shade.
        h, s, v = _rgb_to_hsv(base)
        return [_hsv_to_rgb(h, s, v * 0.82), _hsv_to_rgb(h, s, v * 0.92),
                tuple(base), _hsv_to_rgb(h, s * 0.55, min(1.0, v * 1.12))]
    h, s, v = _rgb_to_hsv(base)
    violet, warm = 0.72, 0.13
    shadow = _hsv_to_rgb(_shift_hue_toward(h, violet, 0.22),
                         min(1.0, s * 1.08 + 0.06), v * 0.52)
    mid = _hsv_to_rgb(_shift_hue_toward(h, violet, 0.10),
                      min(1.0, s * 1.04 + 0.03), v * 0.76)
    high = _hsv_to_rgb(_shift_hue_toward(h, warm, 0.12), s * 0.72,
                       min(1.0, v * 1.14 + 0.05))
    return [shadow, mid, tuple(base), high]


