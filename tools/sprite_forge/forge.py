@dataclass
class ActorSpec:
    name: str
    build: Callable[[], Tuple[Model, Dict[str, Sequence[float]]]]
    clips: List[Clip]
    cell_w: int = 128
    cell_h: int = 112
    pivot_y: int = 98     # feet line in the cell
    # Bigger art pixels: render at PIXEL_SIZE * pixel_scale and let the game
    # draw the sheet pixel_scale times larger, so the character keeps its
    # size on screen but is built from fewer, chunkier pixels.
    pixel_scale: float = 1.0
    # Optional carry socket: (joint_a, joint_b). Their midpoint is exported
    # per frame so the game can pin a carried thing (a grappled foe) to the
    # hands. A pseudo-joint "carry" in the pose sets the carried thing's
    # roll in degrees (its rx).
    socket: Optional[Tuple[str, str]] = None
    # "pixel" (cel-shaded pixel art) or "toon" (smooth cel shading, ink and
    # a rim light in rim_rgb, rendered supersampled and drawn smoothed).
    style: str = "pixel"
    rim_rgb: Optional[Tuple[int, int, int]] = None
    # Spring-driven secondary motion (see clip_frames).
    follow: Optional[Dict[str, Tuple]] = None


SHEET_COLUMNS = 16   # minimum cells per sheet row
MAX_SHEET = 8192     # px; safe texture size on desktop GPUs and WebGL2


def _socket_sample(model, renderer, spec, pose):
    from bpy_extras.object_utils import world_to_camera_view
    sc = bpy.context.scene
    a = model.joints[spec.socket[0]].matrix_world.translation
    b = model.joints[spec.socket[1]].matrix_world.translation
    mid = (a + b) * 0.5
    body = model.joints["chest"].matrix_world.translation if "chest" in \
        model.joints else model.root.matrix_world.translation
    cam = renderer.camera
    p = world_to_camera_view(sc, cam, mid)
    q = world_to_camera_view(sc, cam, body)
    x = p.x * spec.cell_w - spec.cell_w / 2.0
    y = (1.0 - p.y) * spec.cell_h - spec.pivot_y
    roll = pose.get("carry", (0, 0, 0))[0]
    front = 1 if p.z < q.z - 0.02 else 0
    return f"{x:.0f},{y:.0f},{roll:.0f},{front}"


def render_actor(spec: ActorSpec, out_png: str, rel_png: str, log=print):
    """Render every clip in all 8 directions into one packed sheet.

    Cells are packed left to right, top to bottom, SHEET_COLUMNS per row.
    For clip c starting at cell `start`, direction d and frame f:
        cell = start + d * frames + f
    Returns the manifest lines describing the sheet.
    """
    bpy.ops.wm.read_factory_settings(use_empty=True)
    model, base = spec.build()
    renderer = Renderer(spec.cell_w, spec.cell_h, spec.pivot_y,
                        PIXEL_SIZE * spec.pixel_scale,
                        supersample=2 if spec.style == "toon" else 1)
    total = sum(c.frames for c in spec.clips) * len(DIRECTIONS)
    # Roughly square sheets stay inside GPU texture limits for big casts.
    cols = max(SHEET_COLUMNS,
               math.ceil(math.sqrt(total * spec.cell_h / spec.cell_w)))
    rows = (total + cols - 1) // cols
    assert cols * spec.cell_w <= MAX_SHEET and rows * spec.cell_h <= MAX_SHEET, \
        f"{spec.name}: sheet would be {cols * spec.cell_w}x{rows * spec.cell_h}"
    sheet = Image.new("RGBA", (cols * spec.cell_w, rows * spec.cell_h),
                      (0, 0, 0, 0))
    lines = [f"actor {spec.name} {rel_png} {spec.cell_w} {spec.cell_h} "
             f"{spec.cell_w // 2} {spec.pivot_y} {cols}"
             + (f" {spec.pixel_scale:g}" if spec.pixel_scale != 1.0
                or spec.style == "toon" else "")
             + (" smooth" if spec.style == "toon" else "")]
    cell = 0
    sockets = []
    for clip in spec.clips:
        start = cell
        poses = clip_frames(clip, base, model, spec.follow)
        for di, _ in enumerate(DIRECTIONS):
            yaw = di * 45.0
            for f in range(clip.frames):
                pose, offset, rot = poses[f]
                model.pose(pose, offset, rot, yaw)
                img = renderer.frame(model, spec.style, spec.rim_rgb)
                if spec.socket:
                    sockets.append(_socket_sample(model, renderer, spec, pose))
                sheet.alpha_composite(img, ((cell % cols) * spec.cell_w,
                                            (cell // cols) * spec.cell_h))
                cell += 1
        lines.append(f"anim {spec.name} {clip.name} {start} {clip.frames} "
                     f"{clip.fps} {1 if clip.loop else 0}")
        if spec.socket:
            # x,y: pixels from the feet pivot; r: roll (deg); f: 1 = the
            # socket is nearer the camera than his body (draw the foe over him)
            lines.append(f"socket {spec.name} {clip.name} " +
                         " ".join(sockets[start:cell]))
        log(f"  {spec.name}.{clip.name}: {clip.frames} frames x 8 directions")
    sheet.save(out_png)
    return lines
