"""Sprite forge: code-built 3D models -> cel-shaded pixel-art sprite sheets.

Every in-game character and creature is modelled in Python from simple
low-poly parts, posed with a tiny forward-kinematics skeleton, rendered by
Blender (bpy, headless Cycles) from the game's fixed camera in 8 directions,
and turned into pixel art by one shared set of rules:

  * one world-space key light, the same for every asset
  * colour ramps (shadow / mid / base / highlight) derived from each
    material's base colour with the same hue-shift rule
  * a dark outline around the silhouette and on depth breaks inside it
  * one global pixel size (PIXEL_SIZE world units per pixel)

Those shared rules are what make the cast look like one game. Nothing is
painted; nothing is generated by an image model.

Rendering never uses Blender's own shading. Each frame is rendered three
times with flat emission materials that encode material id, surface normal
and depth; the cel shading and outlines are computed here in numpy, so the
look is fully defined by this file.

Run through tools/sprite_forge/build.py, not directly.
"""

