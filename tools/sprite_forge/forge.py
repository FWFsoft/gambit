"""Sprite forge: code-built 3D models -> cel-shaded pixel-art sprite sheets.

Every in-game character and creature is modelled in Python from simple
low-poly parts, posed with a tiny forward-kinematics skeleton, rendered by
Blender (bpy, headless Cycles) from the game's fixed camera in 8 directions,
and turned into pixel art by one shared set of rules:

  * one world-space key light, the same for every asset
  * colour ramps (shadow / mid / base / highlight) derived from each
    material's base colour with the same hue-shift rule
  * a dark outline around the silhouette and on depth breaks inside it
  * one global pixel size (PIXEL_SIZE world units per pixel)

Those shared rules are what make the cast look like one game. Nothing is
painted; nothing is generated by an image model.

Rendering never uses Blender's own shading. Each frame is rendered three
times with flat emission materials that encode material id, surface normal
and depth; the cel shading and outlines are computed here in numpy, so the
look is fully defined by this file.

Run through tools/sprite_forge/build.py, not directly.
"""

import math
import os
import tempfile
from dataclasses import dataclass, field
from typing import Callable, Dict, List, Optional, Sequence, Tuple

import bpy  # must come before bmesh, which bpy registers
import bmesh
import numpy as np
from mathutils import Euler, Matrix, Vector
from PIL import Image

# --------------------------------------------------------------------------
# Global style constants: change these and every asset changes together.
# --------------------------------------------------------------------------

PIXEL_SIZE = 0.0215          # world units per sprite pixel (1.85u hero ~ 75px)
CAMERA_ELEVATION_DEG = 30.0  # matches the 2:1 isometric tiles
KEY_LIGHT = Vector((-0.55, -0.50, 0.68)).normalized()  # front-left-above
FILL_LIGHT = Vector((0.75, 0.20, 0.10)).normalized()   # weak right-side fill
OUTLINE_RGB = (24, 16, 30)
DEPTH_EDGE = 0.10            # world units of depth jump that draws a line

# 8 directions in sheet order. Index i faces screen direction i*45 degrees
# clockwise from straight down (S).
DIRECTIONS = ["S", "SE", "E", "NE", "N", "NW", "W", "SW"]


# --------------------------------------------------------------------------
# Colour ramps
# --------------------------------------------------------------------------

def _rgb_to_hsv(c):
    r, g, b = [x / 255.0 for x in c]
    mx, mn = max(r, g, b), min(r, g, b)
    d = mx - mn
    h = 0.0
    if d > 1e-6:
        if mx == r:
            h = ((g - b) / d) % 6
        elif mx == g:
            h = (b - r) / d + 2
        else:
            h = (r - g) / d + 4
        h /= 6.0
    s = 0.0 if mx < 1e-6 else d / mx
    return h, s, mx


def _hsv_to_rgb(h, s, v):
    h = h % 1.0
    i = int(h * 6)
    f = h * 6 - i
    p, q, t = v * (1 - s), v * (1 - f * s), v * (1 - (1 - f) * s)
    r, g, b = [(v, t, p), (q, v, p), (p, v, t), (p, q, v), (t, p, v), (v, p, q)][i % 6]
    return tuple(int(round(max(0, min(1, x)) * 255)) for x in (r, g, b))


def _shift_hue_toward(h, target, amount):
    d = ((target - h + 0.5) % 1.0) - 0.5
    return h + d * amount


def make_ramp(base, glow=False) -> List[Tuple[int, int, int]]:
    """Shadow, mid, base, highlight. Shadows drift toward violet and lose
    value, highlights drift toward warm yellow and lose saturation: the usual
    pixel-art ramp, applied identically to every material."""
    if glow:
        # Emissive materials (eyes, venom) barely shade.
        h, s, v = _rgb_to_hsv(base)
        return [_hsv_to_rgb(h, s, v * 0.82), _hsv_to_rgb(h, s, v * 0.92),
                tuple(base), _hsv_to_rgb(h, s * 0.55, min(1.0, v * 1.12))]
    h, s, v = _rgb_to_hsv(base)
    violet, warm = 0.72, 0.13
    shadow = _hsv_to_rgb(_shift_hue_toward(h, violet, 0.22),
                         min(1.0, s * 1.08 + 0.06), v * 0.52)
    mid = _hsv_to_rgb(_shift_hue_toward(h, violet, 0.10),
                      min(1.0, s * 1.04 + 0.03), v * 0.76)
    high = _hsv_to_rgb(_shift_hue_toward(h, warm, 0.12), s * 0.72,
                       min(1.0, v * 1.14 + 0.05))
    return [shadow, mid, tuple(base), high]


