@dataclass
class Material:
    name: str
    base: Tuple[int, int, int]
    glow: bool = False
    index: int = 0
    ramp: List[Tuple[int, int, int]] = field(default_factory=list)
    bmat: Optional[object] = None


class Model:
    """A posable model: a hierarchy of joints (empties) with rigid mesh parts.

    Joints are created in rest pose. Conventions (model faces -Y, its left is
    +X, Z is up):
      * a limb hanging down swings FORWARD with a NEGATIVE x rotation
      * a knee bends with a POSITIVE x rotation, an elbow with NEGATIVE x
      * the spine leans forward with a POSITIVE x rotation
      * z rotation twists (positive = turn toward the model's left)
    """

    def __init__(self, name: str):
        self.name = name
        self.materials: Dict[str, Material] = {}
        self.joints: Dict[str, object] = {}
        self.rest: Dict[str, Vector] = {}
        self.root = self._empty("root", None, (0, 0, 0))

    # ---- materials -----------------------------------------------------
    def material(self, name, rgb, glow=False) -> str:
        if name not in self.materials:
            m = Material(name, tuple(rgb), glow, index=len(self.materials) + 1)
            m.ramp = make_ramp(m.base, glow)
            mat = bpy.data.materials.new(f"{self.name}_{name}")
            mat.use_nodes = True
            nt = mat.node_tree
            nt.nodes.clear()
            out = nt.nodes.new("ShaderNodeOutputMaterial")
            em = nt.nodes.new("ShaderNodeEmission")
            # The id pass: material index encoded in the red channel.
            em.inputs["Color"].default_value = (m.index / 255.0, 0.0, 0.0, 1.0)
            nt.links.new(em.outputs[0], out.inputs[0])
            m.bmat = mat
            self.materials[name] = m
        return name

    # ---- joints --------------------------------------------------------
    def _empty(self, name, parent, location):
        obj = bpy.data.objects.new(f"{self.name}_{name}", None)
        bpy.context.scene.collection.objects.link(obj)
        obj.rotation_mode = "XYZ"
        if parent is not None:
            obj.parent = parent
            obj.location = Vector(location) - parent.matrix_world.translation
        else:
            obj.location = Vector(location)
        bpy.context.view_layer.update()
        return obj

    def joint(self, name, parent, location):
        """Add a joint at a world-space rest location."""
        p = self.root if parent is None else self.joints[parent]
        obj = self._empty(name, p, location)
        self.joints[name] = obj
        self.rest[name] = obj.location.copy()
        return name

    # ---- parts ---------------------------------------------------------
    def _attach(self, bm, joint, material, smooth=False):
        mesh = bpy.data.meshes.new(f"{self.name}_mesh")
        bm.to_mesh(mesh)
        bm.free()
        for poly in mesh.polygons:
            poly.use_smooth = smooth
        mesh.materials.append(self.materials[material].bmat)
        obj = bpy.data.objects.new(f"{self.name}_part", mesh)
        bpy.context.scene.collection.objects.link(obj)
        parent = self.root if joint is None else self.joints[joint]
        bpy.context.view_layer.update()
        world = obj.matrix_world.copy()
        obj.parent = parent
        obj.matrix_parent_inverse = parent.matrix_world.inverted()
        obj.matrix_world = world
        return obj

    @staticmethod
    def _transform(bm, center, size, rot_deg=(0, 0, 0)):
        m = (Matrix.Translation(Vector(center)) @
             Euler([math.radians(a) for a in rot_deg], "XYZ").to_matrix().to_4x4() @
             Matrix.Diagonal(Vector((size[0], size[1], size[2], 1.0))))
        bmesh.ops.transform(bm, matrix=m, verts=bm.verts)

    def blob(self, joint, material, center, size, rot=(0, 0, 0), segments=10,
             rings=7, smooth=False):
        """Ellipsoid. size = full extents (x, y, z)."""
        bm = bmesh.new()
        bmesh.ops.create_uvsphere(bm, u_segments=segments, v_segments=rings,
                                  radius=0.5)
        self._transform(bm, center, size, rot)
        return self._attach(bm, joint, material, smooth)

    def box(self, joint, material, center, size, rot=(0, 0, 0), taper=1.0,
            taper_y=None, bevel=0.0):
        """Box, optionally tapered toward +z (taper = top/bottom width)."""
        bm = bmesh.new()
        bmesh.ops.create_cube(bm, size=1.0)
        ty = taper if taper_y is None else taper_y
        for v in bm.verts:
            if v.co.z > 0:
                v.co.x *= taper
                v.co.y *= ty
        if bevel > 0:
            bmesh.ops.bevel(bm, geom=list(bm.edges), offset=bevel, segments=1,
                            affect="EDGES")
        self._transform(bm, center, size, rot)
        return self._attach(bm, joint, material)

    def limb(self, joint, material, start, end, r0, r1, sides=8, cap=True):
        """Tapered cylinder from start to end (world rest positions)."""
        start, end = Vector(start), Vector(end)
        axis = end - start
        length = axis.length
        bm = bmesh.new()
        bmesh.ops.create_cone(bm, cap_ends=cap, segments=sides,
                              radius1=r0, radius2=r1, depth=length)
        # cone is centred on origin along z: move so it spans 0..length
        bmesh.ops.translate(bm, vec=Vector((0, 0, length / 2)), verts=bm.verts)
        rot = Vector((0, 0, 1)).rotation_difference(axis.normalized())
        m = Matrix.Translation(start) @ rot.to_matrix().to_4x4()
        bmesh.ops.transform(bm, matrix=m, verts=bm.verts)
        return self._attach(bm, joint, material)

    # ---- posing --------------------------------------------------------
    def pose(self, pose: Dict[str, Sequence[float]], root_offset=(0, 0, 0),
             root_rot=(0, 0, 0), yaw_deg=0.0):
        for name, obj in self.joints.items():
            r = pose.get(name, (0, 0, 0))
            obj.rotation_euler = Euler([math.radians(a) for a in r], "XYZ")
            obj.location = self.rest[name]
        # Root: yaw for direction, then the animation's own root motion.
        yaw = Matrix.Rotation(math.radians(yaw_deg), 4, "Z")
        local = (Matrix.Translation(Vector(root_offset)) @
                 Euler([math.radians(a) for a in root_rot], "XYZ").to_matrix().to_4x4())
        self.root.matrix_world = yaw @ local
        bpy.context.view_layer.update()


