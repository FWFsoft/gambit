@dataclass
class ActorSpec:
    name: str
    build: Callable[[], Tuple[Model, Dict[str, Sequence[float]]]]
    clips: List[Clip]
    cell_w: int = 128
    cell_h: int = 112
    pivot_y: int = 98     # feet line in the cell


SHEET_COLUMNS = 16   # minimum cells per sheet row
MAX_SHEET = 8192     # px; safe texture size on desktop GPUs and WebGL2


def render_actor(spec: ActorSpec, out_png: str, rel_png: str, log=print):
    """Render every clip in all 8 directions into one packed sheet.

    Cells are packed left to right, top to bottom, SHEET_COLUMNS per row.
    For clip c starting at cell `start`, direction d and frame f:
        cell = start + d * frames + f
    Returns the manifest lines describing the sheet.
    """
    bpy.ops.wm.read_factory_settings(use_empty=True)
    model, base = spec.build()
    renderer = Renderer(spec.cell_w, spec.cell_h, spec.pivot_y)
    total = sum(c.frames for c in spec.clips) * len(DIRECTIONS)
    # Roughly square sheets stay inside GPU texture limits for big casts.
    cols = max(SHEET_COLUMNS,
               math.ceil(math.sqrt(total * spec.cell_h / spec.cell_w)))
    rows = (total + cols - 1) // cols
    assert cols * spec.cell_w <= MAX_SHEET and rows * spec.cell_h <= MAX_SHEET, \
        f"{spec.name}: sheet would be {cols * spec.cell_w}x{rows * spec.cell_h}"
    sheet = Image.new("RGBA", (cols * spec.cell_w, rows * spec.cell_h),
                      (0, 0, 0, 0))
    lines = [f"actor {spec.name} {rel_png} {spec.cell_w} {spec.cell_h} "
             f"{spec.cell_w // 2} {spec.pivot_y} {cols}"]
    cell = 0
    for clip in spec.clips:
        start = cell
        for di, _ in enumerate(DIRECTIONS):
            yaw = di * 45.0
            for f in range(clip.frames):
                denom = clip.frames if clip.loop else max(1, clip.frames - 1)
                pose, offset, rot = sample(clip, f / denom, base)
                model.pose(pose, offset, rot, yaw)
                img = renderer.frame(model)
                sheet.alpha_composite(img, ((cell % cols) * spec.cell_w,
                                            (cell // cols) * spec.cell_h))
                cell += 1
        lines.append(f"anim {spec.name} {clip.name} {start} {clip.frames} "
                     f"{clip.fps} {1 if clip.loop else 0}")
        log(f"  {spec.name}.{clip.name}: {clip.frames} frames x 8 directions")
    sheet.save(out_png)
    return lines
